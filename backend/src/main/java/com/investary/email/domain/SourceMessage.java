package com.investary.email.domain;

import java.time.Instant;
import java.util.Arrays;
import java.util.List;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * An imported email. The original EML in storage is authoritative; header fields are copied from it
 * on import and never changed. Content columns are derived and may be regenerated by reprocessing.
 */
@Entity
@Table(name = "source_messages")
public class SourceMessage {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Enumerated(EnumType.STRING)
    @Column(name = "source_type", nullable = false, updatable = false)
    private SourceType sourceType;

    @Column(name = "storage_key", nullable = false, updatable = false)
    private String storageKey;

    @Column(name = "original_filename", nullable = false, updatable = false)
    private String originalFilename;

    @Column(name = "file_size", nullable = false, updatable = false)
    private long fileSize;

    @Column(name = "content_sha256", nullable = false, updatable = false, length = 64)
    private String contentSha256;

    @Column(name = "message_id", updatable = false)
    private String messageId;

    @Column(name = "sender_address", updatable = false)
    private String senderAddress;

    @Column(name = "sender_name", updatable = false)
    private String senderName;

    /** Newline-separated "Name &lt;address&gt;" entries from To and Cc. */
    @Column(name = "recipient_addresses", updatable = false)
    private String recipientAddresses;

    @Column(name = "subject", updatable = false)
    private String subject;

    @Column(name = "sent_at", updatable = false)
    private Instant sentAt;

    @Column(name = "imported_at", nullable = false, updatable = false)
    private Instant importedAt;

    @Column(name = "brokerage")
    private String brokerage;

    @Column(name = "detected_languages")
    private String detectedLanguages;

    @Column(name = "html_content")
    private String htmlContent;

    @Column(name = "normalized_text")
    private String normalizedText;

    @Enumerated(EnumType.STRING)
    @Column(name = "parsing_status", nullable = false)
    private ParsingStatus parsingStatus;

    @Column(name = "parsing_error")
    private String parsingError;

    protected SourceMessage() {
        // for JPA
    }

    public SourceMessage(SourceType sourceType, String storageKey, String originalFilename, long fileSize, String contentSha256,
                         String messageId, String senderAddress, String senderName, List<String> recipients, String subject,
                         Instant sentAt, Instant importedAt) {
        this.sourceType = sourceType;
        this.storageKey = storageKey;
        this.originalFilename = originalFilename;
        this.fileSize = fileSize;
        this.contentSha256 = contentSha256;
        this.messageId = messageId;
        this.senderAddress = senderAddress;
        this.senderName = senderName;
        this.recipientAddresses = recipients == null || recipients.isEmpty() ? null : String.join("\n", recipients);
        this.subject = subject;
        this.sentAt = sentAt;
        this.importedAt = importedAt;
        this.parsingStatus = ParsingStatus.PARSED;
    }

    public void applyContent(String brokerage, List<String> languages, String htmlContent, String normalizedText,
                             ParsingStatus status, String parsingError) {
        this.brokerage = brokerage;
        this.detectedLanguages = languages == null || languages.isEmpty() ? null : String.join(",", languages);
        this.htmlContent = htmlContent;
        this.normalizedText = normalizedText;
        this.parsingStatus = status;
        this.parsingError = parsingError;
    }

    public UUID getId() {
        return id;
    }

    public SourceType getSourceType() {
        return sourceType;
    }

    public String getStorageKey() {
        return storageKey;
    }

    public String getOriginalFilename() {
        return originalFilename;
    }

    public long getFileSize() {
        return fileSize;
    }

    public String getContentSha256() {
        return contentSha256;
    }

    public String getMessageId() {
        return messageId;
    }

    public String getSenderAddress() {
        return senderAddress;
    }

    public String getSenderName() {
        return senderName;
    }

    public List<String> getRecipients() {
        return recipientAddresses == null ? List.of() : Arrays.asList(recipientAddresses.split("\n"));
    }

    public String getSubject() {
        return subject;
    }

    public Instant getSentAt() {
        return sentAt;
    }

    public Instant getImportedAt() {
        return importedAt;
    }

    public String getBrokerage() {
        return brokerage;
    }

    public List<String> getDetectedLanguages() {
        return detectedLanguages == null ? List.of() : Arrays.asList(detectedLanguages.split(","));
    }

    public String getHtmlContent() {
        return htmlContent;
    }

    public String getNormalizedText() {
        return normalizedText;
    }

    public ParsingStatus getParsingStatus() {
        return parsingStatus;
    }

    public String getParsingError() {
        return parsingError;
    }
}
